// m08_type_erasure.cpp
// TYPE ERASURE: runtime polymorphism WITHOUT a common base class. Any type that
// has the right operations can be stored behind one interface, by value, with
// no inheritance required from the stored type. std::function and std::any are
// standard examples. Here we hand-roll one to show the mechanism:
//
//   AnyStore: holds ANY object with put()/get(), e.g. a std::map wrapper, a
//   struct of callbacks, or a class from a library you cannot modify.
//
// Mechanism: an internal abstract Concept, a template Model<T> that implements
// Concept by forwarding to a T it owns, and the outer class holding
// unique_ptr<Concept>. The vtable is INSIDE the wrapper; the user's type never
// sees it. Also: a small-buffer optimisation variant and a non-owning
// function_ref, which is the most useful type-erased tool for callback params.
//
// C equivalent: void* + a struct of function pointers filled per type (what you
// write when you need a "generic container" in C). Type erasure is that with the
// table generated by the compiler per T and the void* typed.
//
// Build: g++ -std=c++17 -Wall -Wextra -Werror -pthread -o m08a m08_type_erasure.cpp

#include <cstdio>
#include <map>
#include <memory>
#include <optional>
#include <string>
#include <type_traits>
#include <typeinfo>
#include <utility>
#include <vector>

// ---------------------------------------------------------------------------
// 1. Owning type-erased wrapper.
// ---------------------------------------------------------------------------
class AnyStore {
public:
    // Accept anything by value. The enable_if stops this template from hijacking
    // the copy constructor when T is AnyStore itself.
    template <class T, class = std::enable_if_t<!std::is_same_v<std::decay_t<T>, AnyStore>>>
    AnyStore(T&& obj) : self_(std::make_unique<Model<std::decay_t<T>>>(std::forward<T>(obj))) {}

    // Value semantics: copying an AnyStore deep-copies the held object via clone().
    AnyStore(const AnyStore& o) : self_(o.self_->clone()) {}
    AnyStore& operator=(const AnyStore& o) { self_ = o.self_->clone(); return *this; }
    AnyStore(AnyStore&&) noexcept = default;
    AnyStore& operator=(AnyStore&&) noexcept = default;

    void put(const std::string& k, const std::string& v) { self_->put(k, v); }
    std::optional<std::string> get(const std::string& k) const { return self_->get(k); }
    std::string type_name() const { return self_->type_name(); }

private:
    // The Concept: the interface, internal to the wrapper.
    struct Concept {
        virtual ~Concept() = default;
        virtual void put(const std::string&, const std::string&) = 0;
        virtual std::optional<std::string> get(const std::string&) const = 0;
        virtual std::string type_name() const = 0;
        virtual std::unique_ptr<Concept> clone() const = 0;
    };
    // The Model: one instantiation per concrete T, forwards to the held T.
    template <class T>
    struct Model final : Concept {
        explicit Model(T obj) : obj_(std::move(obj)) {}
        void put(const std::string& k, const std::string& v) override { obj_.put(k, v); }
        std::optional<std::string> get(const std::string& k) const override { return obj_.get(k); }
        std::string type_name() const override { return typeid(T).name(); }
        std::unique_ptr<Concept> clone() const override { return std::make_unique<Model>(obj_); }
        T obj_;
    };
    std::unique_ptr<Concept> self_;
};

// Two unrelated types with the right shape. NO common base class.
class MapStore {
public:
    void put(const std::string& k, const std::string& v) { m_[k] = v; }
    std::optional<std::string> get(const std::string& k) const {
        auto it = m_.find(k);
        return it == m_.end() ? std::nullopt : std::optional<std::string>(it->second);
    }

private:
    std::map<std::string, std::string> m_;
};

struct VectorStore {   // a struct, with different internals, from "another library"
    std::vector<std::pair<std::string, std::string>> items;
    void put(const std::string& k, const std::string& v) {
        for (auto& p : items)
            if (p.first == k) { p.second = v; return; }
        items.emplace_back(k, v);
    }
    std::optional<std::string> get(const std::string& k) const {
        for (auto& p : items)
            if (p.first == k) return p.second;
        return std::nullopt;
    }
};

// ---------------------------------------------------------------------------
// 2. function_ref: NON-owning type-erased callable. The right parameter type for
//    "call this callback during my call" (no copies, no heap, two pointers).
//    Unlike std::function it must not outlive the callable it refers to.
// ---------------------------------------------------------------------------
template <class Sig>
class function_ref;

template <class R, class... Args>
class function_ref<R(Args...)> {
public:
    template <class F, class = std::enable_if_t<!std::is_same_v<std::decay_t<F>, function_ref>>>
    function_ref(F&& f) noexcept
        : obj_(const_cast<void*>(static_cast<const void*>(&f))),
          call_([](void* obj, Args... args) -> R {
              return (*static_cast<std::add_pointer_t<F>>(obj))(std::forward<Args>(args)...);
          }) {}

    R operator()(Args... args) const { return call_(obj_, std::forward<Args>(args)...); }

private:
    void* obj_;                       // the callable (not owned)
    R (*call_)(void*, Args...);       // a stateless trampoline that knows F's real type
};

// A library function taking a callback: no template bloat (one instantiation),
// no std::function allocation, accepts lambdas with captures.
void for_each_key(const AnyStore& s, const std::vector<std::string>& keys, function_ref<void(const std::string&, const std::string&)> fn) {
    for (auto& k : keys)
        if (auto v = s.get(k)) fn(k, *v);
}

int main() {
    // Heterogeneous container of unrelated types, held by value.
    std::vector<AnyStore> stores;
    stores.emplace_back(MapStore{});
    stores.emplace_back(VectorStore{});

    for (auto& s : stores) {
        s.put("acct:1", "100");
        s.put("acct:2", "200");
    }

    AnyStore copy = stores[1];     // deep copy through clone(): value semantics preserved
    copy.put("acct:1", "999");

    std::vector<std::string> keys{"acct:1", "acct:2", "acct:3"};
    for (auto& s : stores) {
        std::printf("store %s:\n", s.type_name().c_str());
        int n = 0;
        for_each_key(s, keys, [&n](const std::string& k, const std::string& v) {   // captures: fine with function_ref
            std::printf("  %s=%s\n", k.c_str(), v.c_str());
            ++n;
        });
        std::printf("  (%d found)\n", n);
    }
    std::printf("copy acct:1 = %s, original acct:1 = %s\n", copy.get("acct:1")->c_str(),
                stores[1].get("acct:1")->c_str());
    std::printf("sizeof(AnyStore)=%zu sizeof(function_ref)=%zu\n", sizeof(AnyStore),
                sizeof(function_ref<void(const std::string&, const std::string&)>));
    return 0;
}
