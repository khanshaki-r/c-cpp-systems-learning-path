"""Generate mkdocs.yml for the learning-path site.

The navigation is built from the course folders, so adding a module file is enough to make it
appear on the site. Run from the repository root:

    python site_tools/build_config.py            # public site (private courses left out)
    python site_tools/build_config.py --private  # local build that also shows private courses

CI runs the first form before every build, so the committed mkdocs.yml never drifts.
"""
from __future__ import annotations

