def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--private", action="store_true", help="include private courses (local use only)")
    args = parser.parse_args()
    private_excludes = "" if args.private else "\n".join(f"  {name}/" for name in sorted(PRIVATE))
    text = TEMPLATE.format(user=GITHUB_USER, repo=REPO_NAME, private_excludes=private_excludes)
    text += "\n".join(build_nav(args.private)) + "\n"
    (REPO_ROOT / "mkdocs.yml").write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote mkdocs.yml ({'with' if args.private else 'without'} private courses)")


if __name__ == "__main__":
    main()
